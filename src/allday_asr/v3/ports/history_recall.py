"""Bounded recall dependencies; implementations are assembled by bootstrap."""

from typing import Protocol


class RecallIdentities(Protocol):
    def people(self) -> dict: ...
    def version(self) -> str: ...
    def catalog(self, offset=0) -> dict: ...
    def decide(self, request, actor) -> dict: ...


class RecallRepository(Protocol):
    def chat(self, scope, terms, limit, cancel, deadline) -> tuple: ...
    def recordings(self, scope, terms, limit, cancel, deadline) -> tuple: ...
    def context(self, row, scope) -> list: ...
    def evidence(self, record, origin, role="match") -> dict: ...
    def validate_record(self, record) -> None: ...
    def filter_context(self, records, scope) -> list: ...
    def conversation_evidence(self, records, scope, existing) -> list: ...
    def dataset(self) -> str: ...
    def authorized_scopes(self, scope) -> list: ...
    def changed(self, evidence) -> set: ...
    def identity_changed(self, evidence) -> bool: ...
    def mark_changed(self, row, reason) -> None: ...
    def related_conversations(self, account, scope, cancel, deadline) -> tuple: ...
    def existing_memory(self, scope, terms, cancel, deadline) -> list: ...


class RecallModel(Protocol):
    def __call__(self, payload: dict, cancel) -> dict: ...
