"""Local source maintenance, remote admission and ownership capabilities."""
from collections.abc import Callable
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol


class DailyInventory(Protocol):
    timezone: str

    def scan(self, *, include_today: bool = False, only_dates=None) -> list[dict[str, Any]]: ...


class DailyQueue(Protocol):
    def observe(self, items, *, origin: str = 'RECENT_DAILY') -> list[str]: ...
    def claim(self, items, *, allowed_dates=None, backfill: bool = False) -> dict | None: ...
    def recover_abandoned(self) -> int: ...
    def heartbeat(self, job) -> None: ...
    def finish(self, job, result, *, success, retryable=True, error=None) -> str: ...
    def pending_dates(self, limit: int = 64) -> tuple[str, ...]: ...


class DailyMaintenanceRepository(Protocol):
    path: Path

    def daily_inventory(self, version, *, model, now) -> DailyInventory: ...
    def daily_generation_queue(self, now) -> DailyQueue: ...
    def daily_dirty_ranges(self, limit: int = 64) -> tuple: ...
    def acknowledge_daily_dirty_ranges(self, consumed) -> None: ...


class DailyMaintenanceService(Protocol):
    @property
    def daily_execution_observation(self) -> dict[str, Any]: ...
    def refresh_daily(self, day, timezone_name='Asia/Singapore', *, allow_model=True) -> dict: ...
    def mark_daily_stale(self, day, timezone_name, fingerprint, *, expected_revision=None) -> bool: ...
    def close(self) -> None: ...


DailyOwnership = Callable[[Path], AbstractContextManager[bool]]
